def _update_skill_competency_and_progress(user_id, test_id):
    conn = get_db()
    cur = conn.cursor()

    cur.execute("SELECT competency_applied FROM tests WHERE id = :1", (test_id,))
    already_applied = _fetchone(cur)
    if not already_applied or already_applied["competency_applied"]:
        conn.close()
        return

    cur.execute("SELECT skill_name FROM user_skills WHERE user_id = :1", (user_id,))
    skill_rows = _fetchall(cur)
    declared_skills = {r["skill_name"].strip().lower(): r["skill_name"] for r in skill_rows if r["skill_name"]}

    if not declared_skills:
        cur.execute("UPDATE tests SET competency_applied = 1 WHERE id = :1", (test_id,))
        conn.commit()
        conn.close()
        return

    cur.execute(
        """SELECT q.topic, q.correct_option, ua.selected_option
           FROM test_questions tq
           JOIN questions q ON q.id = tq.question_id
           LEFT JOIN user_answers ua ON ua.test_id = tq.test_id AND ua.question_id = q.id
           WHERE tq.test_id = :1""",
        (test_id,)
    )
    rows = _fetchall(cur)

    matched_any = False
    for r in rows:
        topic_key = (r["topic"] or "").strip().lower()
        if topic_key not in declared_skills:
            continue  

        matched_any = True
        skill_name = declared_skills[topic_key]
        is_correct = 1 if r["selected_option"] and r["selected_option"] == r["correct_option"] else 0

        cur.execute(
            """MERGE INTO skill_competency sc
               USING (SELECT :1 AS user_id, :2 AS skill_name, :3 AS is_correct FROM DUAL) src
               ON (sc.user_id = src.user_id AND sc.skill_name = src.skill_name)
               WHEN MATCHED THEN UPDATE SET
                   sc.correct_count = sc.correct_count + src.is_correct,
                   sc.total_count   = sc.total_count + 1,
                   sc.updated_at    = CURRENT_TIMESTAMP
               WHEN NOT MATCHED THEN INSERT (user_id, skill_name, correct_count, total_count)
                   VALUES (src.user_id, src.skill_name, src.is_correct, 1)""",
            (user_id, skill_name, is_correct)
        )

    if matched_any:
        cur.execute(
            "SELECT correct_count, total_count FROM skill_competency WHERE user_id = :1", (user_id,)
        )
        competency_rows = _fetchall(cur)
        percents = [
            round((c["correct_count"] / c["total_count"]) * 100)
            for c in competency_rows if c["total_count"] > 0
        ]
        overall_percent = round(sum(percents) / len(percents)) if percents else 0

        cur.execute(
            "INSERT INTO progress_snapshots (user_id, test_id, overall_percent) VALUES (:1, :2, :3)",
            (user_id, test_id, overall_percent)
        )

    cur.execute("UPDATE tests SET competency_applied = 1 WHERE id = :1", (test_id,))
    conn.commit()
    conn.close()


def _backfill_skill_competency():
    conn = get_db()
    cur = conn.cursor()
    cur.execute(
        """SELECT DISTINCT t.id, t.user_id FROM tests t
           JOIN test_attempts ta ON ta.test_id = t.id
           WHERE t.user_id IS NOT NULL AND (t.competency_applied IS NULL OR t.competency_applied = 0)"""
    )
    pending = _fetchall(cur)
    conn.close()

    for row in pending:
        _update_skill_competency_and_progress(row["user_id"], row["id"])


