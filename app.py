def _dict_row(cursor, row):
    if row is None:
        return None
    columns = [col[0].lower() for col in cursor.description]
    result = {}
    for col, val in zip(columns, row):
        if isinstance(val, oracledb.LOB):
            val = val.read()
        result[col] = val
    return result


def _dict_rows(cursor, rows):
    if not rows:
        return []
    columns = [col[0].lower() for col in cursor.description]
    result = []
    for row in rows:
        d = {}
        for col, val in zip(columns, row):
            if isinstance(val, oracledb.LOB):
                val = val.read()
            d[col] = val
        result.append(d)
    return result


def _fetchone(cur):
    row = cur.fetchone()
    return _dict_row(cur, row)


def _fetchall(cur):
    rows = cur.fetchall()
    return _dict_rows(cur, rows)


def _getid(var):
    val = var.getvalue()
    if isinstance(val, list):
        return int(val[0]) if val else None
    return int(val) if val is not None else None


def _ensure_column(conn, table, column, coltype_and_default):
    cur = conn.cursor()
    cur.execute(
        """SELECT COUNT(*) FROM user_tab_columns
           WHERE UPPER(table_name) = UPPER(:1) AND UPPER(column_name) = UPPER(:2)""",
        (table, column)
    )
    row = cur.fetchone()
    if row and row[0] == 0:
        plsql = f"""
        BEGIN
            EXECUTE IMMEDIATE 'ALTER TABLE {table} ADD {column} {coltype_and_default}';
        EXCEPTION WHEN OTHERS THEN NULL;
        END;
        """
        cur.execute(plsql)
        conn.commit()


